// Reproducible extraction of the upstream data engine, not its ST application host.
import ts from 'typescript'
import { readFile, writeFile, mkdir } from 'node:fs/promises'
import { resolve, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'
import { createHash } from 'node:crypto'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const sourceRoot = resolve(process.argv[2] ?? resolve(root, '../../drafts/MagVarUpdate-beta'))
const destination = resolve(root, 'src/runtime/vendor/mvu')
await mkdir(destination, { recursive: true })
const files = {
  'update_variables.ts': 'src/function/update_variables.ts',
  'schema.ts': 'src/function/schema.ts',
  'variable_def.ts': 'src/variable_def.ts',
  'common.ts': 'util/common.ts',
}
const imports = {
  '@/function/schema': './schema.js',
  '@/variable_def': './variable_def.js',
  '@util/common': './common.js',
}
const provenance = {}
const definitions = ts.createSourceFile('variable_def.ts',
  await readFile(resolve(sourceRoot, files['variable_def.ts']), 'utf8'), ts.ScriptTarget.Latest, true)
const typeNames = new Set(definitions.statements
  .filter(node => ts.isTypeAliasDeclaration(node) || ts.isInterfaceDeclaration(node))
  .map(node => node.name.text))
for (const [name, path] of Object.entries(files)) {
  const raw = await readFile(resolve(sourceRoot, path), 'utf8')
  provenance[path] = createHash('sha256').update(raw).digest('hex')
  const source = ts.createSourceFile(name, raw, ts.ScriptTarget.Latest, true)
  const result = ts.transform(source, [context => {
    const visit = node => {
      if (ts.isImportDeclaration(node)) {
        const from = node.moduleSpecifier.text
        if (['@/i18n', '@/store', '@/util'].includes(from)) return undefined
        if (name === 'common.ts' && !['json5', 'jsonrepair'].includes(from)) return undefined
        if (imports[from]) {
          let clause = node.importClause
          if (from === '@/variable_def' && clause?.namedBindings && ts.isNamedImports(clause.namedBindings)) {
            clause = ts.factory.updateImportClause(clause, clause.isTypeOnly, clause.name,
              ts.factory.updateNamedImports(clause.namedBindings, clause.namedBindings.elements.map(specifier =>
                ts.factory.updateImportSpecifier(specifier, typeNames.has((specifier.propertyName ?? specifier.name).text),
                  specifier.propertyName, specifier.name))))
          }
          return ts.factory.updateImportDeclaration(node, node.modifiers,
            clause, ts.factory.createStringLiteral(imports[from]), node.attributes)
        }
      }
      if (ts.isFunctionDeclaration(node) && node.name?.text === 'handleVariablesInMessage') return undefined
      if (name === 'common.ts' && node.parent === source && !ts.isImportDeclaration(node)
        && !(ts.isFunctionDeclaration(node) && ['correctlyMerge', 'parseString', 'literalYamlify'].includes(node.name?.text))) return undefined
      if (ts.isExpressionStatement(node)) {
        const expression = ts.isAwaitExpression(node.expression) ? node.expression.expression : node.expression
        if (ts.isCallExpression(expression) && (expression.expression.getText(source) === 'eventEmit'
          || expression.expression.getText(source).startsWith('console.')))
          return ts.isBlock(node.parent) ? undefined : ts.factory.createBlock([])
      }
      if (ts.isIfStatement(node) && node.expression.getText(source).includes('useDataStore()')) return undefined
      return ts.visitEachChild(node, visit, context)
    }
    return node => ts.visitNode(node, visit)
  }])
  let output = ts.createPrinter().printFile(result.transformed[0])
  result.dispose()
  if (name === 'update_variables.ts') {
    output = output.replace('variables: MvuData): Promise<boolean>', 'variables: MvuData, diagnostics: Array<{ command: string; content: string }> = []): Promise<boolean>')
    if (!output.includes('diagnostics: Array')) throw new Error('Upstream updateVariables signature changed')
    output = output.replace('error_info = {', 'diagnostics.push({ command, content });\n        error_info = {')
  }
  const prelude = [
    '// @ts-nocheck',
    '// Generated by scripts/vendor-mvu.mjs. Upstream MIT license: LICENSE-MVU.',
    '// Only ST storage, notification and author event integration were removed.',
    "import _ from 'lodash';",
    ...(name === 'common.ts' || name === 'update_variables.ts' ? ["import * as YAML from 'yaml';"] : []),
    ...(name === 'common.ts' ? ["import { tr } from '../../mvu-adapter.js';"] : []),
    ...(name === 'update_variables.ts' ? [
      "import { isJsonPatch, tr, substitudeMacros } from '../../mvu-adapter.js';",
    ] : []),
  ].join('\n')
  await writeFile(resolve(destination, name), `${prelude}\n${output}`)
}
await writeFile(resolve(destination, 'LICENSE-MVU'), await readFile(resolve(sourceRoot, 'LICENSE')))
await writeFile(resolve(destination, 'provenance.json'), `${JSON.stringify({
  source: 'https://github.com/MagicalAstrogy/MagVarUpdate',
  snapshot: 'User-provided MagVarUpdate-beta, 2026-10-07; includes local modifications',
  sha256: provenance,
  omitted: ['ST message persistence', 'UI notifications', 'author event callbacks'],
}, null, 2)}\n`)
